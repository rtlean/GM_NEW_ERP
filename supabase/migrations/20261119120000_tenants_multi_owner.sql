-- US-3.3: locatário com contratos de vários locadores e CPF/CNPJ único.
-- Só aditivo: nada é renomeado, apagado ou tem o tipo alterado.
-- Coluna owner_id de tenants fica como está (não é mais a fonte da verdade).

-- Cidade do locador (US-3.2 deixou para depois).
alter table public.owners add column if not exists city text;

-- CPF/CNPJ limpo do locatário. A coluna cpf antiga guarda CPF e também CNPJ.
alter table public.tenants add column if not exists document text;
update public.tenants
   set document = regexp_replace(cpf, '[^0-9]', '', 'g')
 where document is null and cpf is not null;
create unique index if not exists tenants_company_document_key
  on public.tenants (company_id, document)
  where document is not null;

-- Ligação locatário <-> locador (um locatário pode ter imóveis de vários locadores).
create table if not exists public.tenant_owners (
  id bigint generated by default as identity primary key,
  company_id integer not null default 1,
  tenant_id integer not null references public.tenants (id),
  owner_id integer not null references public.owners (id),
  created_at timestamptz not null default now(),
  constraint tenant_owners_unico unique (company_id, tenant_id, owner_id)
);
create index if not exists tenant_owners_tenant_id_idx on public.tenant_owners (tenant_id);
create index if not exists tenant_owners_owner_id_idx on public.tenant_owners (owner_id);
alter table public.tenant_owners enable row level security;

-- Copia o vínculo atual (tenants.owner_id) para a nova tabela.
insert into public.tenant_owners (company_id, tenant_id, owner_id)
select coalesce(company_id, 1), id, owner_id
  from public.tenants
 where owner_id is not null
on conflict (company_id, tenant_id, owner_id) do nothing;
